import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { _electron } from 'playwright';
import electron from 'electron';
import { createBackup } from '../backup.js';

test('desktop backup and confirmed restore preserve records across a full restart; diagnostics omit private content', async () => {
  const storage = await mkdtemp(path.join(tmpdir(), 'dev-tracker-records-ui-'));
  const launch = () => _electron.launch({ executablePath: process.env.DEV_TRACKER_EXE || electron,
    args: process.env.DEV_TRACKER_EXE ? [] : ['.'], env: { ...process.env, DEV_TRACKER_TEST_DATA: storage } });
  let desktop;
  try {
    const project = path.join(storage, 'private-project'); await mkdir(project);
    const source = path.join(project, 'source.js'); await writeFile(source, 'private source');
    const backup = path.join(storage, 'backup.json'), diagnostic = path.join(storage, 'export.jsonl');
    desktop = await launch(); let page = await desktop.firstWindow();
    await page.locator('#details-toggle').click();
    await page.waitForFunction(() => document.getElementById('window-context').textContent.length > 0);
    const dialogs = async (open, save, confirm = 0) => desktop.evaluate(({ dialog }, choices) => {
      dialog.showOpenDialog = async () => ({ canceled: !choices.open, filePaths: choices.open ? [choices.open] : [] });
      dialog.showSaveDialog = async () => ({ canceled: !choices.save, filePath: choices.save });
      dialog.showMessageBox = async (_, options) => { globalThis.restorePrompt = options; return { response: choices.confirm }; };
    }, { open, save, confirm });
    await dialogs(project, null); await page.locator('#switch-project').click();
    await page.locator('#project-path').getByText(project, { exact: true }).waitFor();
    await page.locator('#map-tab').click(); await page.locator('.node').first().click(); await page.locator('#developer-details > summary').click();
    const request = async text => {
      await page.locator('#requirement').fill(text); await page.locator('#request button').click();
      await page.locator('#requirements').getByText(text).waitFor();
    };
    await request('private-record-before-backup');
    await dialogs(null, null);
    assert.equal(await page.evaluate(() => window.desktop.backupRecords()), false);
    await assert.rejects(access(backup), { code: 'ENOENT' }, 'canceling backup creates no output');
    await dialogs(null, backup);
    await page.locator('#backup-records').click(); await page.waitForFunction(() => !document.getElementById('backup-records').disabled);
    const archive = JSON.parse(await readFile(backup, 'utf8'));
    assert.equal(archive.format, 'dev-tracker-records');
    assert.ok(archive.entries.some(entry => entry.content.includes('private-record-before-backup')));
    assert.equal(archive.entries.some(entry => entry.path.includes('source.js')), false, 'a records backup must never package project source');
    await request('private-record-after-backup');
    const before = await createBackup(storage);
    await dialogs(null, null);
    assert.equal(await page.evaluate(() => window.desktop.restoreRecords()), false);
    await dialogs(backup, null, 0);
    assert.equal(await page.evaluate(() => window.desktop.restoreRecords()), false);
    assert.deepEqual((await createBackup(storage)).entries, before.entries, 'both restore cancellation paths preserve all stored records');
    const invalid = path.join(storage, 'invalid.json'); await writeFile(invalid, JSON.stringify({ ...archive, entries: [...archive.entries, { path: '../source.js', content: '{}' }] }));
    await dialogs(invalid, null, 1);
    await assert.rejects(page.evaluate(() => window.desktop.restoreRecords()), /Invalid or duplicate backup path/);
    assert.deepEqual((await createBackup(storage)).entries, before.entries, 'invalid restore must fail before any record replacement');
    await page.evaluate(async () => { await fetch('/mcp', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ secret: 'private-request-body' }) }); });
    await dialogs(null, diagnostic);
    await page.locator('#export-diagnostics').click(); await page.waitForFunction(() => !document.getElementById('export-diagnostics').disabled);
    const text = await readFile(diagnostic, 'utf8'), entries = text.trim().split('\n').map(JSON.parse);
    assert.ok(entries.some(entry => entry.event === 'startup'));
    assert.ok(entries.some(entry => entry.event === 'listen'));
    assert.ok(entries.some(entry => entry.event === 'mcp_http'));
    for (const entry of entries) for (const key of Object.keys(entry)) assert.ok(['time', 'event', 'stage', 'name', 'code', 'method', 'status', 'durationMs'].includes(key));
    for (const secret of [project, storage, 'private-record', 'private-request-body', 'Invalid or duplicate']) assert.equal(text.includes(secret), false);
    await mkdir('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/records-desktop.png' });
    await page.setViewportSize({ width: 375, height: 812 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'the new header controls must fit narrow screens');
    const boxes = await page.locator('header > button:not([hidden])').evaluateAll(buttons => buttons.map(button => { const r = button.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom }; }));
    for (let a = 0; a < boxes.length; a++) for (let b = a + 1; b < boxes.length; b++) assert.ok(boxes[a].right <= boxes[b].x || boxes[b].right <= boxes[a].x || boxes[a].bottom <= boxes[b].y || boxes[b].bottom <= boxes[a].y, 'header buttons must not overlap');
    await page.screenshot({ path: 'test-results/records-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1280, height: 820 });
    const marker = path.join(storage, 'relaunch.txt');
    await desktop.evaluate(({ app }, file) => { app.relaunch = () => process.getBuiltinModule('fs').writeFileSync(file, 'relaunch requested'); }, marker);
    await dialogs(backup, null, 1);
    const stopped = desktop.waitForEvent('close');
    await page.locator('#restore-records').click().catch(error => { if (!/closed/.test(error.message)) throw error; });
    await stopped; desktop = undefined;
    assert.equal(await readFile(marker, 'utf8'), 'relaunch requested', 'confirmed restore exits and requests a fresh process');
    desktop = await launch(); page = await desktop.firstWindow();
    await page.locator('#details-toggle').click();
    await page.locator('#project-path').getByText(project, { exact: true }).waitFor(); await page.locator('#map-tab').click(); await page.locator('#developer-details > summary').click();
    await page.locator('#requirements').getByText('private-record-before-backup').waitFor();
    assert.equal(await page.locator('#requirements').getByText('private-record-after-backup').count(), 0, 'fresh process must read the restored archive, not cached later records');
    assert.equal(await readFile(source, 'utf8'), 'private source', 'restoring tracker records must leave project source intact');
    await request('record-saved-before-normal-close');
    const closed = desktop.waitForEvent('close');
    await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.close())).catch(error => { if (!/closed/.test(error.message)) throw error; });
    await closed; desktop = undefined;
    const closedEntries = (await readFile(path.join(storage, 'diagnostics.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
    assert.deepEqual(closedEntries.filter(entry => entry.event === 'close').map(entry => entry.stage), ['server', 'desktop'], 'normal exit waits for service shutdown before saving one desktop close event');
    desktop = await launch(); page = await desktop.firstWindow();
    await page.locator('#details-toggle').click();
    await page.locator('#project-path').getByText(project, { exact: true }).waitFor(); await page.locator('#map-tab').click(); await page.locator('#developer-details > summary').click();
    await page.locator('#requirements').getByText('record-saved-before-normal-close').waitFor();
    await desktop.evaluate(({ dialog }) => { dialog.showSaveDialog = () => new Promise(resolve => { globalThis.finishCanceledBackup = () => resolve({ canceled: true }); }); });
    await page.locator('#backup-records').click();
    assert.equal(await desktop.evaluate(() => typeof globalThis.finishCanceledBackup), 'function');
    const pendingClosed = desktop.waitForEvent('close');
    await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.close()));
    await desktop.evaluate(() => globalThis.finishCanceledBackup()).catch(error => { if (!/closed/.test(error.message)) throw error; });
    await pendingClosed; desktop = undefined;
  } finally {
    if (desktop) await desktop.close();
    assert.equal(path.dirname(storage), path.resolve(tmpdir()));
    assert.ok(path.basename(storage).startsWith('dev-tracker-records-ui-'));
    await rm(storage, { recursive: true, force: true });
  }
});
