import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { startServer } from '../server.js';

test('MCP and UI share persisted state, reject bad requests, and never label reports as verified', async () => {
  const storage = await mkdtemp(path.join(tmpdir(), 'dev-tracker-mcp-'));
  const server = await startServer({ storage, port: 0 });
  const url = `http://127.0.0.1:${server.address().port}`;
  const client = new Client({ name: 'integration-test', version: '1' });
  const project = await mkdtemp(path.join(tmpdir(), 'dev-tracker-mcp-project-'));
  try {
    await server.selectProject(project);
    await client.connect(new StreamableHTTPClientTransport(new URL(url + '/mcp')));
    assert.deepEqual((await client.listTools()).tools.map(t => t.name).sort(), ['bind_session', 'append_journal', 'get_journal', 'get_overview', 'get_diff', 'get_handoff', 'get_map', 'get_node', 'update_node', 'get_evidence', 'run_tests', 'link_evidence', 'record_decision', 'get_decisions', 'set_acceptance_plan', 'record_quality_review'].sort());
    assert.equal((await client.callTool({ name: 'get_map', arguments: {} })).isError, true, 'central MCP requires explicit project binding');
    const binding = JSON.parse((await client.callTool({ name: 'bind_session', arguments: { projectRoot: project, label: 'Integration chat' } })).content[0].text);
    const tool = (name, args = {}) => client.callTool({ name, arguments: { ...args, sessionId: binding.sessionId } });
    const handoff = async () => JSON.parse((await tool('get_handoff')).content[0].text);
    assert.equal((await handoff()).context.sessionId, binding.sessionId);
    const call = args => tool('update_node', args);
    assert.equal((await call({ id: 'missing', action: 'start' })).isError, true);
    assert.equal((await call({ id: 'root', action: 'add', text: 'MCP 任务' })).isError, undefined);
    let state = await (await fetch(url + '/api/state')).json();
    const id = state.nodes[1].id;
    await call({ id, action: 'start' });
    await call({ id, action: 'record', text: '尚未运行测试' });
    state = await (await fetch(url + '/api/state')).json();
    assert.equal(state.nodes[1].statusSource, 'ai');
    assert.equal(state.nodes[1].notes[0].source, 'ai');
    assert.notEqual(state.nodes[1].status, 'verified');
    assert.equal((await call({ id, action: 'submit' })).isError, undefined);
    assert.equal((await call({ id, action: 'accept' })).isError, true, 'MCP cannot impersonate user acceptance');
    assert.equal((await tool('get_node', { id })).isError, undefined);
    const manual = async action => {
      const snapshot = await fetch(url + '/api/state').then(r => r.json());
      return fetch(url + '/api/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id, action, sessionId: snapshot.context.sessionId }) });
    };
    assert.equal((await manual('accept')).status, 200);
    state = await (await fetch(url + '/api/state')).json();
    assert.equal(state.nodes[1].status, 'accepted'); assert.equal(state.nodes[1].statusSource, 'manual');
    assert.equal((await manual('accept')).status, 400, 'cannot accept twice or outside review');
    await call({ id, action: 'request', text: '用户验收后提出新需求' });
    state = await (await fetch(url + '/api/state')).json();
    assert.equal(state.nodes[1].status, 'pending', 'new scope invalidates current acceptance');
    await call({ id, action: 'submit' }); await call({ id, action: 'reopen' });
    assert.equal((await manual('accept')).status, 400, 'reopened work must be submitted again');
    await server.evidence.select(project);
    await writeFile(path.join(project, 'example.py'), 'value = 1');
    await server.evidence.scan();
    const changeId = server.evidence.get().changes[0].id;
    const diff = await tool('get_diff', { changeId });
    assert.equal(JSON.parse(diff.content[0].text).available, false, 'non-Git folders do not get fictional code diffs');
    assert.equal((await tool('get_diff', { changeId: 'missing' })).isError, true);
    const link = id => tool('link_evidence', { kind: 'file', changeId, id });
    assert.equal((await link('missing')).isError, true);
    assert.equal((await link(id)).isError, undefined);
    const linked = (await (await fetch(url + '/api/evidence')).json()).changes[0];
    assert.equal(linked.path, 'example.py', 'observed association works independently of programming language');
    assert.equal(linked.node, id); assert.equal(linked.association.source, 'ai');
    let transfer = await handoff();
    assert.match(transfer.markdown, /example\.py/);
    assert.ok(transfer.markdown.includes(id), 'node IDs allow the next chat to resume the same task');
    assert.match(transfer.markdown, /AI|ai/);
    await writeFile(path.join(project, 'proof.test.cjs'), "require('node:test')('proof', () => require('node:assert/strict').equal(1, 1));");
    await tool('run_tests', { id });
    await writeFile(path.join(project, 'example.py'), 'value = 2');
    transfer = await handoff();
    assert.match(transfer.markdown, /需重新验证/, 'export scans before reporting freshness');
    assert.equal((await (await fetch(url + '/api/evidence')).json()).tests[0].current, false);
    const uiHandoff = await (await fetch(url + '/api/handoff.json')).json();
    const mcpHandoff = await handoff();
    assert.equal(uiHandoff.snapshot.project.root, mcpHandoff.snapshot.project.root, 'UI and bound MCP describe the same project');
    assert.equal(uiHandoff.snapshot.project.fingerprint, mcpHandoff.snapshot.project.fingerprint);
    assert.equal((await link(null)).isError, undefined);
    assert.equal(server.evidence.get().changes[0].node, null);
    assert.equal((await fetch(url + '/mcp', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://example.com' }, body: '{}' })).status, 403);
  } finally {
    await client.close();
    await new Promise(resolve => server.close(resolve));
    assert.equal(path.dirname(storage), path.resolve(tmpdir()));
    assert.ok(path.basename(storage).startsWith('dev-tracker-mcp-'));
    await rm(storage, { recursive: true, force: true });
    assert.equal(path.dirname(project), path.resolve(tmpdir()));
    await rm(project, { recursive: true, force: true });
  }
});
