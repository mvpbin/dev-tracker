import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { _electron } from 'playwright';
import electron from 'electron';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { writeFile, readFile } from 'node:fs/promises';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

test('independent desktop windows keep projects and simultaneous AI tasks separate', async () => {
  const storage = await mkdtemp(path.join(tmpdir(), 'dev-tracker-windows-'));
  let desktop;
  const clients = [];
  try {
    const roots = [path.join(storage, 'project-a'), path.join(storage, 'project-b')];
    await Promise.all(roots.map(root => mkdir(root)));
    desktop = await _electron.launch({ timeout: 15000, executablePath: process.env.DEV_TRACKER_EXE || electron, args: process.env.DEV_TRACKER_EXE ? [] : ['.'], env: { ...process.env, DEV_TRACKER_TEST_DATA: storage } });
    const first = await desktop.firstWindow();
    await first.locator('#details-toggle').click();
    await first.waitForFunction(() => document.getElementById('window-context').textContent.length > 0);
    const select = async (page, root) => {
      await desktop.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, root);
      await page.locator('#switch-project').click();
      await page.locator('#project-path').getByText(root, { exact: true }).waitFor();
    };
    const nextWindow = async page => {
      const pending = desktop.waitForEvent('window');
      await page.locator('#new-window').click();
      const next = await pending;
      await next.locator('#details-toggle').click();
      await next.waitForFunction(() => document.getElementById('window-context').textContent.length > 0);
      return next;
    };
    const state = page => page.evaluate(async () => (await fetch('api/state')).json());
    const connect = async page => {
      const client = new Client({ name: 'window-test', version: '1' });
      await client.connect(new StreamableHTTPClientTransport(new URL('mcp', page.url())));
      clients.push(client);
      return client;
    };
    const update = async (client, action, id = 'root', text) => {
      const response = await client.callTool({ name: 'update_node', arguments: { action, id, ...(text ? { text } : {}) } });
      assert.ok(!response.isError, JSON.stringify(response));
    };
    await select(first, roots[0]);
    const second = await nextWindow(first);
    await select(second, roots[1]);
    const one = await connect(first), two = await connect(second);
    await Promise.all([update(one, 'add', 'root', 'A 的独立任务'), update(two, 'add', 'root', 'B 的独立任务')]);
    let a = await state(first), b = await state(second);
    assert.equal(a.context.projectRoot, roots[0]);
    assert.equal(b.context.projectRoot, roots[1]);
    assert.notEqual(a.context.sessionId, b.context.sessionId);
    assert.ok(!a.nodes.some(node => node.title === 'B 的独立任务'));
    assert.ok(!b.nodes.some(node => node.title === 'A 的独立任务'));
    const taskA = a.nodes.find(node => node.title === 'A 的独立任务');
    await update(one, 'start', taskA.id);
    await update(two, 'start', b.nodes.find(node => node.title === 'B 的独立任务').id);
    const third = await nextWindow(first);
    await select(third, roots[0]);
    const three = await connect(third);
    await update(three, 'add', 'root', 'A 的另一会话任务');
    a = await state(third);
    const other = a.nodes.find(node => node.title === 'A 的另一会话任务');
    await update(three, 'start', other.id);
    a = await state(first);
    assert.equal(a.nodes.filter(node => node.status === 'active').length, 2, 'starting another chat does not pause the original chat');
    assert.notEqual(a.nodes.find(node => node.id === taskA.id).owner.sessionId, a.nodes.find(node => node.id === other.id).owner.sessionId);
    await first.locator('#map-tab').click();
    await first.locator('#broadcast-title').getByText(/A 的独立任务.*A 的另一会话任务/).waitFor();
    await first.waitForFunction(() => document.querySelectorAll('#links path.ai-active').length === 2);
    await first.screenshot({ path: 'test-results/multi-window-desktop.png' });
    await first.setViewportSize({ width: 375, height: 812 });
    await first.screenshot({ path: 'test-results/multi-window-mobile.png' });
    const width = await first.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }));
    assert.equal(width.scroll, width.client, 'window and session controls fit narrow displays');
    await second.close();
    await update(one, 'record', taskA.id, '另一个窗口关闭后仍保存到项目 A');
    assert.equal((await state(first)).nodes.find(node => node.id === taskA.id).notes.at(-1).text, '另一个窗口关闭后仍保存到项目 A');
    const gitRoot = path.join(storage, 'git-project');
    await mkdir(gitRoot);
    await writeFile(path.join(gitRoot, 'feature.txt'), 'original');
    const git = async (...args) => promisify(execFile)('git', args, { cwd: gitRoot });
    await git('init'); await git('add', '.');
    await git('-c', 'user.name=Desktop Test', '-c', 'user.email=desktop@test.invalid', 'commit', '-m', 'initial');
    await select(third, gitRoot);
    const parallelOpened = desktop.waitForEvent('window');
    await third.locator('#parallel-window').click();
    const parallel = await parallelOpened;
    await parallel.waitForFunction(() => document.getElementById('window-context').textContent.length > 0);
    const isolated = await state(parallel);
    assert.notEqual(isolated.context.projectRoot, gitRoot, 'parallel action opens an isolated work directory');
    assert.equal(isolated.context.worktree.sourceRoot, gitRoot, 'the copy preserves its origin for later review');
    assert.match(isolated.context.worktree.branch, /^dev-tracker\//);
    await writeFile(path.join(isolated.context.projectRoot, 'feature.txt'), 'parallel changes');
    assert.equal(await readFile(path.join(gitRoot, 'feature.txt'), 'utf8'), 'original', 'parallel code changes do not alter the original folder');
    const parallelClient = await connect(parallel);
    const handoff = JSON.parse((await parallelClient.callTool({ name: 'get_handoff', arguments: {} })).content[0].text);
    assert.equal(handoff.snapshot.project.root, isolated.context.projectRoot, 'MCP observes the parallel window folder');
    assert.equal(handoff.context.worktree.sourceRoot, gitRoot);
    await parallel.screenshot({ path: 'test-results/parallel-window-desktop.png' });
  } finally {
    await Promise.allSettled(clients.map(client => client.close()));
    await desktop?.close();
    await rm(storage, { recursive: true, force: true });
  }
});
